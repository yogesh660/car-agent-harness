"""Tiny SVG builder for the architecture images on the case-study page.

Kept dependency-free on purpose: the images are generated by `make site` and committed, so
anyone can regenerate them without a design tool. Colours match site/style.css.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from html import escape

FONT = "Manrope, Inter, 'Segoe UI', Helvetica, Arial, sans-serif"
MONO = "'DM Mono', ui-monospace, Menlo, Consolas, monospace"

# fill, stroke, accent per kind of box
KINDS = {
    "model": ("#1a1733", "#8c7cff", "#aaa7ff"),
    "code": ("#0f2128", "#56d9ff", "#8fe6ff"),
    "data": ("#0f2219", "#74df9b", "#a3ecbf"),
    "ops": ("#221c10", "#f3c26b", "#f7d797"),
    "io": ("#15151d", "#8a8a96", "#d0d0d5"),
}


@dataclass
class Box:
    x: float
    y: float
    w: float
    h: float
    title: str
    sub: str = ""
    tag: str = ""
    kind: str = "io"
    planned: bool = False

    @property
    def cx(self) -> float:
        return self.x + self.w / 2

    @property
    def cy(self) -> float:
        return self.y + self.h / 2

    def edge(self, side: str) -> tuple[float, float]:
        return {
            "l": (self.x, self.cy),
            "r": (self.x + self.w, self.cy),
            "t": (self.cx, self.y),
            "b": (self.cx, self.y + self.h),
        }[side]


@dataclass
class Diagram:
    w: int
    h: int
    title: str = ""
    parts: list[str] = field(default_factory=list)

    def group(
        self, x: float, y: float, w: float, h: float, label: str, planned: bool = False
    ) -> None:
        dash = ' stroke-dasharray="6 6"' if planned else ""
        self.parts.append(
            f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="18" fill="#ffffff05" '
            f'stroke="#ffffff1f"{dash}/>'
            f'<text x="{x + 18}" y="{y + 26}" font-family="{MONO}" font-size="12" '
            f'letter-spacing="1.6" fill="#9a9aa6">{escape(label.upper())}</text>'
        )

    def box(self, b: Box) -> Box:
        fill, stroke, accent = KINDS[b.kind]
        dash = ' stroke-dasharray="5 5"' if b.planned else ""
        opacity = ' opacity="0.78"' if b.planned else ""
        out = [
            f"<g{opacity}>",
            f'<rect x="{b.x}" y="{b.y}" width="{b.w}" height="{b.h}" rx="12" fill="{fill}" '
            f'stroke="{stroke}" stroke-width="1.4"{dash}/>',
        ]
        ty = b.y + 26
        if b.tag:
            tag = b.tag.upper() + ("  ·  PLANNED" if b.planned else "")
            out.append(
                f'<text x="{b.x + 14}" y="{ty - 4}" font-family="{MONO}" font-size="10.5" '
                f'letter-spacing="1.2" fill="{accent}">{escape(tag)}</text>'
            )
            ty += 18
        out.append(
            f'<text x="{b.x + 14}" y="{ty}" font-family="{FONT}" font-size="16" font-weight="700" '
            f'fill="#f5f5f7">{escape(b.title)}</text>'
        )
        for i, line in enumerate(filter(None, b.sub.split("\n"))):
            out.append(
                f'<text x="{b.x + 14}" y="{ty + 21 + i * 18}" font-family="{FONT}" font-size="13" '
                f'fill="#a6a6b0">{escape(line)}</text>'
            )
        out.append("</g>")
        self.parts.append("".join(out))
        return b

    def arrow(
        self,
        a: tuple[float, float],
        b: tuple[float, float],
        label: str = "",
        dashed: bool = False,
        bend: str = "",
    ) -> None:
        (x1, y1), (x2, y2) = a, b
        if bend == "hv":  # horizontal then vertical
            d = f"M{x1},{y1} H{x2} V{y2}"
        elif bend == "vh":
            d = f"M{x1},{y1} V{y2} H{x2}"
        elif bend == "vhv":
            mid = (y1 + y2) / 2
            d = f"M{x1},{y1} V{mid} H{x2} V{y2}"
        elif bend == "hvh":
            mid = (x1 + x2) / 2
            d = f"M{x1},{y1} H{mid} V{y2} H{x2}"
        else:
            d = f"M{x1},{y1} L{x2},{y2}"
        dash = ' stroke-dasharray="5 5"' if dashed else ""
        self.parts.append(
            f'<path d="{d}" fill="none" stroke="#7a7a88" stroke-width="1.6"{dash} '
            f'marker-end="url(#arrow)"/>'
        )
        if label:
            lx, ly = (x1 + x2) / 2, (y1 + y2) / 2
            self.parts.append(
                f'<rect x="{lx - len(label) * 3.6 - 8}" y="{ly - 11}" width="{len(label) * 7.2 + 16}" '
                f'height="20" rx="10" fill="#0c0e16" stroke="#ffffff1a"/>'
                f'<text x="{lx}" y="{ly + 4}" text-anchor="middle" font-family="{MONO}" '
                f'font-size="11" fill="#b9b9c4">{escape(label)}</text>'
            )

    def path(
        self, points: list[tuple[float, float]], label: str = "", dashed: bool = False
    ) -> None:
        d = "M" + " L".join(f"{x},{y}" for x, y in points)
        dash = ' stroke-dasharray="5 5"' if dashed else ""
        self.parts.append(
            f'<path d="{d}" fill="none" stroke="#7a7a88" stroke-width="1.6"{dash} marker-end="url(#arrow)"/>'
        )
        if label:
            (x1, y1), (x2, y2) = points[len(points) // 2 - 1], points[len(points) // 2]
            self.label((x1 + x2) / 2, (y1 + y2) / 2, label)

    def label(self, lx: float, ly: float, text: str) -> None:
        self.parts.append(
            f'<rect x="{lx - len(text) * 3.6 - 8}" y="{ly - 11}" width="{len(text) * 7.2 + 16}" '
            f'height="20" rx="10" fill="#0c0e16" stroke="#ffffff1a"/>'
            f'<text x="{lx}" y="{ly + 4}" text-anchor="middle" font-family="{MONO}" '
            f'font-size="11" fill="#b9b9c4">{escape(text)}</text>'
        )

    def legend(self, x: float, y: float) -> None:
        items = [
            ("model", "Model"),
            ("code", "Deterministic code"),
            ("data", "Data"),
            ("ops", "Quality & delivery"),
        ]
        cx = x
        for kind, text in items:
            fill, stroke, _ = KINDS[kind]
            self.parts.append(
                f'<rect x="{cx}" y="{y - 10}" width="14" height="14" rx="4" fill="{fill}" stroke="{stroke}"/>'
                f'<text x="{cx + 22}" y="{y + 1}" font-family="{MONO}" font-size="11.5" fill="#9a9aa6">{escape(text)}</text>'
            )
            cx += 36 + len(text) * 7.4
        self.parts.append(
            f'<rect x="{cx}" y="{y - 10}" width="14" height="14" rx="4" fill="none" stroke="#9a9aa6" stroke-dasharray="3 3"/>'
            f'<text x="{cx + 22}" y="{y + 1}" font-family="{MONO}" font-size="11.5" fill="#9a9aa6">Planned</text>'
        )

    def svg(self) -> str:
        title = f"<title>{escape(self.title)}</title>" if self.title else ""
        return (
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {self.w} {self.h}" '
            f'width="{self.w}" height="{self.h}" role="img">{title}'
            '<defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" '
            'markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="#7a7a88"/>'
            "</marker></defs>"
            f'<rect width="{self.w}" height="{self.h}" rx="24" fill="#0b0c12"/>'
            + "".join(self.parts)
            + "</svg>\n"
        )
